import {readFileSync,writeFileSync} from 'node:fs';
const root='member-experience/';
const assets=Object.fromEntries(['programme-client.js','programme-joining.js','programme-style.css'].map(name=>[name,readFileSync(root+name,'utf8')]));
writeFileSync(root+'programme-assets.mjs','// Generated by prepare-programme.mjs.\nexport const programmeAssets='+JSON.stringify(assets)+';\n');
writeFileSync(root+'programme-joining-page.mjs','// Generated by prepare-programme.mjs.\nexport const programmeJoiningHTML='+JSON.stringify(readFileSync(root+'programme-joining.html','utf8'))+';\n');
