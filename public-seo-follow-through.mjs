for(const change of [...FOLLOW_THROUGH.contextLinks,...FOLLOW_THROUGH.ownerCopy]){
 const list=byPath.get(change.path)||[];list.push(change);byPath.set(change.path,list);
}
export const FOLLOW_THROUGH_PATHS=[...new Set([...byPath.keys(),...FOLLOW_THROUGH.restoreArchives])];
export function applyFollowThrough(html,path){
 const changes=byPath.get(path)||[];
 for(const change of changes){
  if(html.includes(change.after))continue;
  // Fail closed if the exact reviewed paragraph has disappeared or repeats.
  if(html.split(change.before).length!==2)continue;
  html=html.replace(change.before,change.after);
 }
 if(FOLLOW_THROUGH.restoreArchives.includes(path)){
  const tag='<meta name="robots" content="noindex,follow">';
  if(html.split(tag).length===2)html=html.replace(tag,'<meta name="robots" content="index,follow">');
 }
 return html;
}
export async function withSeoFollowThrough(response,request){
 const url=new URL(request.url),path=url.pathname;
 if(!FOLLOW_THROUGH_PATHS.includes(path)||!['GET','HEAD'].includes(request.method)||response.status!==200||!response.headers.get('content-type')?.includes('text/html'))return response;
 const before=await response.text(),after=applyFollowThrough(before,path),headers=new Headers(response.headers);
 if(FOLLOW_THROUGH.restoreArchives.includes(path)&&after.includes('<meta name="robots" content="index,follow">')){
  // Clear only the reviewed quarantine header. Preserve any unrelated header.
  if(headers.get('x-robots-tag')?.trim().toLowerCase()==='noindex, follow')headers.delete('x-robots-tag');
 }
 for(const name of ['content-length','content-encoding','etag','last-modified'])headers.delete(name);
 headers.set('cache-control','public, max-age=300');
 headers.set('x-shift-seo-follow-through','2026-10-06-v3');
 return new Response(request.method==='HEAD'?null:after,{status:response.status,statusText:response.statusText,headers});
}

