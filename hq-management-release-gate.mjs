import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const git=(...a)=>execFileSync('git',a,{encoding:'utf8'}).trim();
export const BASE='e9d8ca70';
export const SOURCE='38b0cc50eeeda7e713c2ce25ebf9c9543cdbb793';
const payload=['HQ-MANAGEMENT-RELEASE.md','hq-ai-v2.js','hq-management-acceptance.mjs','hq-management-api.mjs','hq-management-browser-acceptance.mjs','worker.js'];
const plumbing=['hq-management-release-gate.mjs','.github/workflows/hq-management-release.yml'];
git('merge-base','--is-ancestor',BASE,'HEAD');
git('merge-base','--is-ancestor',SOURCE,'HEAD');
const changed=git('diff','--name-only',BASE,'HEAD').split('\n').filter(Boolean);
assert(changed.every(p=>[...payload,...plumbing].includes(p)),'Release contains changes outside the approved HQ scope');
for(const p of payload)assert.equal(git('rev-parse','HEAD:'+p),git('rev-parse',SOURCE+':'+p),'Approved HQ payload changed: '+p);
assert.equal(git('diff','--name-only',BASE,'HEAD','--','wrangler.jsonc','package.json','package-lock.json','frontend','public','assets','shift-coach','worker-entry-v6.js'),'','Public assets, routes, coaching or configuration changed');
assert.equal(git('diff','--name-only'),'','Tracked working source changed');
console.log('PASS exact approved HQ payload; public assets, entrypoints and configuration preserved; no migrations or publication.');
